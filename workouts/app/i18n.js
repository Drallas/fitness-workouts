// Taal van de interface: Engels (standaard), Nederlands en Spaans.
// Alleen de tekst van de app wordt vertaald; oefeningsnamen en gegenereerde titels blijven zoals ze zijn.
const KEY = "fw-lang";
export const LANGS = [
  { code: "en", label: "English", locale: "en-GB" },
  { code: "nl", label: "Nederlands", locale: "nl-NL" },
  { code: "es", label: "Español", locale: "es-ES" },
];

export function getLang() {
  try {
    const l = localStorage.getItem(KEY);
    if (LANGS.some((x) => x.code === l)) return l;
  } catch (e) {}
  return "en";
}
export function setLang(code) {
  try { localStorage.setItem(KEY, code); } catch (e) {}
}
export const locale = () => LANGS.find((x) => x.code === getLang()).locale;

// t("key", { n: 3 }) zoekt de vertaling; ontbreekt die, dan de Engelse tekst.
export function t(key, vars = {}) {
  const s = (DICT[getLang()] && DICT[getLang()][key]) ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Zet de vertaling op de vaste tekst van een pagina: data-i18n (tekst), data-i18n-html (met opmaak),
// data-i18n-attr="placeholder:key;aria-label:key" (attributen). Ook het taalattribuut van de pagina.
export function initPage() {
  document.documentElement.lang = getLang();
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":").map((x) => x.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}

